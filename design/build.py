#!/usr/bin/env python3
"""Build keygraph.css and kg-theme.js from tokens.json.

    python3 design/build.py            # writes design/keygraph.css and design/kg-theme.js
    python3 design/build.py --inline   # also writes design/keygraph.inline.css with the fonts embedded as base64
    python3 design/build.py --check    # prints WCAG contrast for every text/background pair and fails under 4.5:1
    python3 design/build.py --export-static   # also copies the explorer's design assets into src/keygraph/static/

The explorer generator should inline keygraph.inline.css (fonts embedded, no fetches) plus kg-theme.js and src/kg-diagram.js.
"""
import base64, json, math, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
T = json.loads((HERE / "tokens.json").read_text())


def key(k):
    return str(k).replace(".", "-")


def type_var(name, s):
    fam = "var(--kg-font-mono)" if s.get("family") == "mono" else "var(--kg-font-sans)"
    return f"{s['weight']} {s['size']}px/{s['line']}px {fam}"


def theme_vars(c):
    out = []
    for k, v in c.items():
        if k == "graph":
            for gk, gv in v.items():
                if gk == "hop":
                    out += [f"--kg-graph-hop-{i}: {x};" for i, x in enumerate(gv)]
                else:
                    out.append(f"--kg-graph-{gk}: {gv};")
        elif k == "schema":
            out += [f"--kg-schema-{i}: {x};" for i, x in enumerate(v)]
        elif k == "schema-generated":
            continue
        else:
            out.append(f"--kg-{k}: {v};")
    return out


def font_faces(inline):
    out = []
    for fam, f in T["font"]["files"].items():
        p = HERE / f["file"]
        src = (f"url(data:font/woff2;base64,{base64.b64encode(p.read_bytes()).decode()}) format('woff2')"
               if inline else f"url('{f['file']}') format('woff2')")
        out.append(f"@font-face {{ font-family: '{fam}'; src: {src}; font-weight: {f['weight']}; "
                   f"font-style: normal; font-display: swap; }}")
    return "\n".join(out)


def css(inline=False):
    root = [f"--kg-font-sans: {T['font']['sans']};", f"--kg-font-mono: {T['font']['mono']};"]
    for n, s in T["type"].items():
        if n.startswith("$"):
            continue
        root.append(f"--kg-type-{n}: {type_var(n, s)};")
        if "tracking" in s:
            root.append(f"--kg-track-{n}: {s['tracking']};")
        if s.get("family") == "mono":
            root.append(f"--kg-type-{n}-size: {s['size']}px;")
    root += [f"--kg-space-{key(k)}: {v}px;" for k, v in T["space"].items()]
    root += [f"--kg-radius-{k}: {v}px;" for k, v in T["radius"].items()]
    root += [f"--kg-size-{k}: {v}px;" for k, v in T["size"].items()]
    root += [f"--kg-motion-{k}: {v};" for k, v in T["motion"].items() if not k.startswith("$") and not k.startswith("ease")]
    root += [f"--kg-{k}: {v};" for k, v in T["motion"].items() if k.startswith("ease")]
    root += [f"--kg-z-{k}: {v};" for k, v in T["z"].items()]
    light, dark = theme_vars(T["color"]["light"]), theme_vars(T["color"]["dark"])
    ind = lambda xs, n=2: "\n".join(" " * n + x for x in xs)
    head = ("/* keygraph.css - generated by design/build.py from tokens.json. Edit tokens.json or src/components.css,\n"
            "   never this file. Fonts: Inter and JetBrains Mono, SIL Open Font License 1.1 (see fonts/). */\n")
    vars_ = (f":root {{\n{ind(root)}\n  color-scheme: light;\n{ind(light)}\n}}\n"
             f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme=\"light\"]) {{\n    color-scheme: dark;\n{ind(dark, 4)}\n  }}\n}}\n"
             f":root[data-theme=\"dark\"] {{\n  color-scheme: dark;\n{ind(dark)}\n}}\n")
    comps = (HERE / "src" / "components.css").read_text()
    return head + font_faces(inline) + "\n\n" + vars_ + "\n" + comps


def theme_js():
    th = {n: {"graph": T["color"][n]["graph"], "schema": T["color"][n]["schema"],
              "gen": T["color"][n]["schema-generated"], "canvas": T["color"][n]["canvas"]} for n in ("light", "dark")}
    js = (HERE / "src" / "kg-theme.src.js").read_text()
    return js.replace("/*__THEMES__*/null", json.dumps(th, indent=2)).replace("/*__GEOMETRY__*/null", json.dumps(T["graph"], indent=2))


STATIC = HERE.parent / "src" / "keygraph" / "static"
EXPORT = {  # what keygraph.html inlines; the wheel ships these copies, so it never needs design/
    "keygraph.inline.css": HERE / "keygraph.inline.css",
    "kg-theme.js": HERE / "kg-theme.js",
    "kg-diagram.js": HERE / "src" / "kg-diagram.js",
    "dagre-1.1.4.min.js": HERE / "vendor" / "dagre-1.1.4.min.js",
    "DAGRE_LICENSE": HERE / "vendor" / "DAGRE_LICENSE",
    "OFL-Inter.txt": HERE / "fonts" / "OFL-Inter.txt",
    "OFL-JetBrainsMono.txt": HERE / "fonts" / "OFL-JetBrainsMono.txt",
    "keygraph-logo.svg": HERE / "logo" / "keygraph-logo-light.svg",
    "keygraph-mark.svg": HERE / "logo" / "keygraph-mark-light.svg",
    "favicon.svg": HERE / "logo" / "favicon.svg",
}


def export_static() -> list[str]:
    STATIC.mkdir(parents=True, exist_ok=True)
    for name, src in EXPORT.items():
        (STATIC / name).write_bytes(src.read_bytes())
    return sorted(EXPORT)


def lum(h):
    h = h.lstrip("#"); rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(rgb[0]) + 0.7152 * f(rgb[1]) + 0.0722 * f(rgb[2])


def ratio(a, b):
    x, y = sorted([lum(a), lum(b)], reverse=True); return (x + .05) / (y + .05)


def check():
    bad = 0
    for n in ("light", "dark"):
        c = T["color"][n]
        for fg in ("text", "text-2", "text-3", "accent-text", "success", "warning", "danger", "info"):
            for bg in ("surface", "surface-2"):
                r = ratio(c[fg], c[bg]); ok = r >= 4.5; bad += not ok
                print(f"{n:5} {fg:12} on {bg:10} {r:5.2f} {'ok' if ok else 'FAIL'}")
        for i, s in enumerate(c["schema"]):
            r = ratio(s, c["canvas"]); ok = r >= 3; bad += not ok
            print(f"{n:5} schema-{i} on canvas {r:5.2f} {'ok' if ok else 'FAIL (needs 3:1 for graphics)'}")
        r = ratio(c["text-on-accent"], c["accent"]); print(f"{n:5} text-on-accent {r:5.2f}")
    return bad


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(1 if check() else 0)
    (HERE / "keygraph.css").write_text(css())
    (HERE / "kg-theme.js").write_text(theme_js())
    if "--inline" in sys.argv or "--export-static" in sys.argv:
        (HERE / "keygraph.inline.css").write_text(css(inline=True))
    print("wrote keygraph.css, kg-theme.js" + (", keygraph.inline.css" if "--inline" in sys.argv or "--export-static" in sys.argv else ""))
    if "--export-static" in sys.argv:
        print("exported to src/keygraph/static/:", ", ".join(export_static()))
